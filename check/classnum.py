# Verify: the lattices <1,1,3> and <1,3,3> are alone in their (spinor) genus, by Kneser's neighbour method.
# For p in {5,7,11}: every p-neighbour of L is isometric to L (explicit isometry found by brute force).
from fractions import Fraction as F
from itertools import product
import math
def neighbours(d, p):
    """L = Z^3 with diagonal form d. Yield Gram matrices (Fractions->ints) of all p-neighbours."""
    n=3; seen=set(); out=[]
    Q=lambda x: sum(d[i]*x[i]*x[i] for i in range(n))
    B=lambda x,y: sum(d[i]*x[i]*y[i] for i in range(n))
    for x in product(range(p),repeat=n):
        if all(c==0 for c in x): continue
        # normalise projective point: first nonzero coordinate = 1
        k=next(i for i in range(n) if x[i]); inv=pow(x[k],-1,p); xn=tuple((c*inv)%p for c in x)
        if xn in seen: continue
        seen.add(xn)
        if Q(xn)%p: continue
        # lift so that Q(x) ≡ 0 mod p^2: x + p*t
        lifted=None
        for t in product(range(p),repeat=n):
            y=tuple(xn[i]+p*t[i] for i in range(n))
            if Q(y)%(p*p)==0: lifted=y; break
        assert lifted is not None
        x0=lifted
        # L_x = {y in L : B(x0,y) ≡ 0 mod p}; neighbour = L_x + Z x0/p
        # basis of L_x: solve linear congruence c·y ≡ 0 mod p, c_i = d_i x0_i mod p
        c=[(d[i]*x0[i])%p for i in range(n)]
        j=next(i for i in range(n) if c[i]); cj_inv=pow(c[j],-1,p)
        basis=[]
        for i in range(n):
            if i==j: continue
            y=[0]*n; y[i]=1; y[j]=(-c[i]*cj_inv)%p; basis.append(y)
        y=[0]*n; y[j]=p; basis.append(y)
        # generators: basis (3 vectors) + x0/p ; get a Z-basis by HNF-like reduction over rationals
        gens=[[F(v) for v in b] for b in basis]+[[F(v,p) for v in x0]]
        bas=zbasis(gens)
        G=[[sum(d[k]*bas[i][k]*bas[j2][k] for k in range(n)) for j2 in range(n)] for i in range(n)]
        assert all(g.denominator==1 for row in G for g in row), G
        out.append([[int(g) for g in row] for row in G])
    return out
def zbasis(gens):
    """Z-basis of lattice generated by rational vectors (rank 3) via integer row reduction on scaled matrix."""
    den=1
    for g in gens:
        for v in g: den=den*v.denominator//math.gcd(den,v.denominator)
    M=[[int(v*den) for v in g] for g in gens]
    # Hermite normal form by row operations
    rows=[r[:] for r in M]; res=[]; col=0
    for col in range(3):
        piv=[r for r in rows if r[col]!=0]
        rest=[r for r in rows if r[col]==0]
        while len(piv)>1:
            piv.sort(key=lambda r:abs(r[col]))
            a=piv[0]
            new=[a]
            for r in piv[1:]:
                q=r[col]//a[col]; r2=[r[i]-q*a[i] for i in range(3)]
                if r2[col]!=0: new.append(r2)
                else: rest.append(r2)
            piv=new
        if piv: res.append(piv[0])
        rows=rest
    assert len(res)==3 and all(all(v==0 for v in r) for r in rows)
    return [[F(v,den) for v in r] for r in res]
def det3(G):
    return (G[0][0]*(G[1][1]*G[2][2]-G[1][2]*G[2][1])-G[0][1]*(G[1][0]*G[2][2]-G[1][2]*G[2][0])+G[0][2]*(G[1][0]*G[2][1]-G[1][1]*G[2][0]))
def isometric_to_diag(G,d,bound=60):
    """find integer vectors e1,e2,e3 with G-norms d1,d2,d3, pairwise G-orthogonal, det ±1."""
    q=lambda x: sum(G[i][j]*x[i]*x[j] for i in range(3) for j in range(3))
    b=lambda x,y: sum(G[i][j]*x[i]*y[j] for i in range(3) for j in range(3))
    vecs={}
    R=range(-bound,bound+1)
    need=set(d)
    for x in product(R,repeat=3):
        v=q(x)
        if v in need: vecs.setdefault(v,[]).append(x)
    for e1 in vecs.get(d[0],[]):
        for e2 in vecs.get(d[1],[]):
            if b(e1,e2): continue
            for e3 in vecs.get(d[2],[]):
                if b(e1,e3) or b(e2,e3): continue
                D=(e1[0]*(e2[1]*e3[2]-e2[2]*e3[1])-e1[1]*(e2[0]*e3[2]-e2[2]*e3[0])+e1[2]*(e2[0]*e3[1]-e2[1]*e3[0]))
                if abs(D)==1: return True
    return False
def lll_like(G):
    """crude reduction: repeatedly subtract to shrink diagonal (pairwise Gauss)"""
    import copy
    G=[row[:] for row in G]
    changed=True
    while changed:
        changed=False
        for i in range(3):
            for j in range(3):
                if i==j: continue
                if G[j][j]==0: continue
                q=round(F(G[i][j],G[j][j]))
                if q:
                    # b_i -= q b_j
                    for k in range(3): G[i][k]-=q*G[j][k]
                    for k in range(3): G[k][i]-=q*G[k][j]
                    changed=True
    return G
for d in ([1,1,3],[1,3,3]):
    for p in (5,7,11):
        nb=neighbours(d,p)
        ok=0
        for G in nb:
            assert det3(G)==d[0]*d[1]*d[2], (G,det3(G))
            Gr=lll_like(G)
            assert isometric_to_diag(Gr,d,bound=6), (d,p,G,Gr)
            ok+=1
        print("form",d,"p =",p,": number of p-neighbours",len(nb),"(expected p+1 =",p+1,") all isometric to the form:",ok==len(nb))
